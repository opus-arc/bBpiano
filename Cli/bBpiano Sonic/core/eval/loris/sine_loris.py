# ==========================
# synthesis
# ==========================

fs = 44100
duration = 2.2

t = np.arange(int(fs * duration)) / fs
signal = np.zeros_like(t)

# 直接使用 Loris 第一个 breakpoint 的 amplitude_linear 和 phase_radians
for freq, partial_duration, amp, phase, _ in partials:
    n = min(len(t), int(partial_duration * fs))
    if n <= 0:
        continue

    tt = t[:n]
    partial = amp * np.sin(2 * np.pi * freq * tt + phase)

    # 每个 partial 自己做一个短 fade out，避免突然截断 click
    partial_fade = min(int(0.005 * fs), n)
    if partial_fade > 1:
        partial[-partial_fade:] *= np.linspace(1, 0, partial_fade)

    signal[:n] += partial

# Normalize
peak = np.max(np.abs(signal))
if peak > 0:
    signal /= peak
signal *= 0.95

# 5 ms fade in/out
fade = int(0.005 * fs)
window = np.ones_like(signal)
window[:fade] = np.linspace(0, 1, fade)
window[-fade:] = np.linspace(1, 0, fade)
signal *= window

print("Playing...")
sd.play(signal, fs)
sd.wait()
