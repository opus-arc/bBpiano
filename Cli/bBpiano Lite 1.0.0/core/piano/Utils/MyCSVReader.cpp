std::vector<LossConstant> MyCSVReader::getLossConstant() {
    std::vector<LossConstant> constants(std::begin(kLossConstants), std::end(kLossConstants));

    for (auto& loss : constants) {
        loss.g = std::clamp(loss.g, 0.0, 1.0);
        loss.a_1 = std::clamp(loss.a_1, -0.98, 0.98);
    }

    return constants;
}

DispersionConstant MyCSVReader::getDispersionConstantByMidi(int midi_n) {
    for (const auto& dispersion : kDispersionConstants) {
        if (dispersion.midi_n == midi_n) {
            DispersionConstant result = dispersion;
            result.a1 = std::clamp(result.a1, -0.999, 0.999);
            return result;
        }
    }

    return {};
}
