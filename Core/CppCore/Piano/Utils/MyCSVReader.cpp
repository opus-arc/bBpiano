RT425StringParameter MyCSVReader::getRT425WrappedStringParameterByMidi(int midi_n) {
    midi_n = std::clamp(midi_n, 21, 108);

    const auto* best = std::begin(kRT425WrappedStringParameters);
    int bestDistance = std::abs(best->key - midi_n);

    for (const auto& parameter : kRT425WrappedStringParameters) {
        if (parameter.key == midi_n) {
            return parameter;
        }

        const int distance = std::abs(parameter.key - midi_n);
        if (distance < bestDistance) {
            best = &parameter;
            bestDistance = distance;
        }
    }

    return *best;
}

RT425HammerParameter MyCSVReader::getRT425HammerParameterByMidi(int midi_n) {
    midi_n = std::clamp(midi_n, 21, 108);

    const int noteIndex = midi_n - 20;
    const double i = static_cast<double>(noteIndex);

    RT425HammerParameter parameter;
    parameter.key = midi_n;
    parameter.note_index = noteIndex;
    parameter.mass_kg = -6.2348e-5 * i + 0.0112;
    parameter.P = 2.4295e-4 * i * i - 0.007703 * i + 2.337;
    parameter.K = std::pow(10.0, 5.3097e-2 * i + 7.6425);
    parameter.R = parameter.K * std::pow(10.0, -(0.04366 * i + 2.294));

    return parameter;
}
