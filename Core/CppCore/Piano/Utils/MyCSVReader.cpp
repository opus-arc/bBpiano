double MyCSVReader::estimateRT425WrappedB(double frequencyHz) {
    
    // 三段五次多项式拟合
    
    if (frequencyHz <= 0.0)
        return 0.0;

    double m = 69.0 + 12.0 * std::log2(frequencyHz / 440.0);
    m = std::clamp(m, 21.0, 108.0);

    double x;
    double logB;

    if (m <= 40.0)
    {
        // MIDI 21 ~ 40, centered at 30.5
        x = m - 30.5;

        logB =
            (((((2.54806566903736653e-06 * x
              + 8.03461935278017411e-05) * x
              - 6.64620288983106667e-05) * x
              - 1.03258147873218752e-02) * x
              - 6.92839446648340213e-02) * x
              - 9.70572185529191778e+00);
    }
    else if (m <= 93.0)
    {
        // MIDI 41 ~ 93, centered at 67
        x = m - 67.0;

        logB =
            (((((-1.87988791111451152e-08 * x
              + 8.77002026184926955e-07) * x
              + 3.76384731490010101e-06) * x
              - 8.65747703933558732e-04) * x
              + 1.61743542297792947e-01) * x
              - 5.80561195559259424e+00);
    }
    else
    {
        // MIDI 94 ~ 108, centered at 101
        x = m - 101.0;

        logB =
            (((((-7.57789770666236690e-06 * x
              - 1.06586625433944474e-05) * x
              + 6.27044076479977403e-04) * x
              + 1.50887311294244336e-03) * x
              + 1.29806284482145484e-01) * x
              - 8.64530118699994410e-01);
    }

    return std::exp(logB);
}

std::vector<LossConstant> MyCSVReader::getLossConstant() {
    std::vector<LossConstant> constants(std::begin(kLossConstants), std::end(kLossConstants));

    for (auto& loss : constants) {
        loss.g = std::clamp(loss.g, 0.0, 1.0);
        loss.a_1 = std::clamp(loss.a_1, -0.98, 0.98);
    }

    return constants;
}

